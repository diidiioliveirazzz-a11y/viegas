CREATE DATABASE IF NOT EXISTS viegas_barber
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE viegas_barber;

CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(120) NULL,
  email VARCHAR(254) NULL UNIQUE,
  password VARCHAR(255) NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'CLIENT',
  phone VARCHAR(40) NULL,
  has_subscription TINYINT(1) NOT NULL DEFAULT 0,
  subscription_ends_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS services (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  description TEXT NULL,
  price DECIMAL(10,2) NOT NULL,
  duration INT NOT NULL,
  image VARCHAR(500) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS subscriptions (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  plan VARCHAR(80) NOT NULL DEFAULT '2 cortes + 2 barbas',
  price DECIMAL(10,2) NOT NULL DEFAULT 40,
  cuts_remaining INT NOT NULL DEFAULT 2,
  beards_remaining INT NOT NULL DEFAULT 2,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING_CASH',
  starts_at DATETIME NULL,
  ends_at DATETIME NULL,
  paid_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS appointments (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  service_id CHAR(36) NOT NULL,
  date DATE NOT NULL,
  start_time CHAR(5) NOT NULL,
  end_time CHAR(5) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
  notes TEXT NULL,
  style_ref VARCHAR(160) NULL,
  is_silent TINYINT(1) NOT NULL DEFAULT 0,
  music_request VARCHAR(160) NULL,
  companion_id CHAR(36) NULL,
  companion_name VARCHAR(120) NULL,
  duo_group_id CHAR(36) NULL,
  loyalty_awarded TINYINT(1) NOT NULL DEFAULT 0,
  review_available_at DATETIME NULL,
  subscription_id CHAR(36) NULL,
  subscription_credit_restored TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (service_id) REFERENCES services(id),
  FOREIGN KEY (subscription_id) REFERENCES subscriptions(id)
);

CREATE TABLE IF NOT EXISTS blocked_times (
  id CHAR(36) PRIMARY KEY,
  date DATE NOT NULL,
  start_time CHAR(5) NOT NULL,
  end_time CHAR(5) NOT NULL,
  reason VARCHAR(200) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reviews (
  id CHAR(36) PRIMARY KEY,
  appointment_id CHAR(36) NOT NULL UNIQUE,
  user_id CHAR(36) NOT NULL,
  rating INT NOT NULL,
  comment TEXT NULL,
  private_notes TEXT NULL,
  top_length_feedback VARCHAR(80) NULL,
  beard_line_feedback VARCHAR(80) NULL,
  is_private TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (appointment_id) REFERENCES appointments(id),
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS settings (
  id VARCHAR(20) PRIMARY KEY,
  min_advance_hours INT NOT NULL DEFAULT 8,
  open_time CHAR(5) NOT NULL DEFAULT '09:00',
  close_time CHAR(5) NOT NULL DEFAULT '19:00',
  lunch_start CHAR(5) NOT NULL DEFAULT '13:00',
  lunch_end CHAR(5) NOT NULL DEFAULT '14:00',
  barber_name VARCHAR(80) NOT NULL DEFAULT 'Diogo Viegas',
  shop_name VARCHAR(80) NOT NULL DEFAULT 'Viegas Barber',
  address VARCHAR(200) NOT NULL DEFAULT 'Rua Principal, Lisboa',
  phone VARCHAR(40) NOT NULL DEFAULT '+351 912 345 678',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hair_styles (
  id CHAR(36) PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(80) NOT NULL,
  description TEXT NULL,
  image_url TEXT NOT NULL,
  likes INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS media_assets (
  id CHAR(36) PRIMARY KEY,
  data LONGBLOB NOT NULL,
  mime VARCHAR(80) NOT NULL DEFAULT 'image/webp',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS client_hair_history (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  service_name VARCHAR(120) NOT NULL,
  style VARCHAR(160) NULL,
  photo_url TEXT NOT NULL,
  notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS loyalty (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL UNIQUE,
  points INT NOT NULL DEFAULT 0,
  visits INT NOT NULL DEFAULT 0,
  tier VARCHAR(20) NOT NULL DEFAULT 'Bronze',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS rewards (
  id CHAR(36) PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  description TEXT NOT NULL,
  points_cost INT NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS products (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  description TEXT NULL,
  price DECIMAL(10,2) NOT NULL,
  stock INT NOT NULL DEFAULT 10,
  category VARCHAR(80) NOT NULL,
  image_url TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orders (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  total DECIMAL(10,2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS order_items (
  id CHAR(36) PRIMARY KEY,
  order_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  quantity INT NOT NULL DEFAULT 1,
  price DECIMAL(10,2) NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(id),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE IF NOT EXISTS notifications (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  title VARCHAR(160) NOT NULL,
  message TEXT NOT NULL,
  `read` TINYINT(1) NOT NULL DEFAULT 0,
  type VARCHAR(40) NOT NULL DEFAULT 'INFO',
  action_url VARCHAR(200) NULL,
  dedupe_key VARCHAR(160) NULL UNIQUE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS waitlist (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  service_id CHAR(36) NULL,
  date DATE NOT NULL,
  time_slot CHAR(5) NULL,
  is_duo TINYINT(1) NOT NULL DEFAULT 0,
  notified TINYINT(1) NOT NULL DEFAULT 0,
  offer_expires_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (service_id) REFERENCES services(id)
);
